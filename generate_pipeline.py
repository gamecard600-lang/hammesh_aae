async def generate_audios():
    # Using gu-IN-DhwaniNeural for a soft, realistic, crystal-clear human narration
    voice = "gu-IN-DhwaniNeural"
    print(f"🎙️ Generating Realistic Gujarati Voiceovers using {voice}...")
    for scene in scenes:
        audio_filename = f"scene_{scene['id']}.mp3"
        comm = edge_tts.Communicate(scene["text"], voice, rate="-3%")
        await comm.save(audio_filename)
        print(f"  ✅ Saved {audio_filename}")

if __name__ == "__main__":
    asyncio.run(generate_audios())
