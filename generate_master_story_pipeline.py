async def generate_audios():
    print("🎙️ Generating 8 Scene Master Gujarati Voiceovers using gu-IN-NiranjanNeural...")
    os.makedirs("assets/videos", exist_ok=True)
    for scene in scenes:
        mp3_file = f"assets/videos/master_scene_{scene['id']}.mp3"
        wav_file = f"assets/videos/master_scene_{scene['id']}.wav"

        print(f"  Generating Scene {scene['id']} Audio...")
        comm = edge_tts.Communicate(scene["text"], "gu-IN-NiranjanNeural", rate="-3%")
        await comm.save(mp3_file)

        # Convert to WAV for exact timing decoding
        subprocess.run(
            f'ffmpeg -i {mp3_file} -y {wav_file}',
            shell=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL
        )

if __name__ == "__main__":
    asyncio.run(generate_audios())
    print("✅ Generated all 8 Master Scene Gujarati audio files successfully!")
